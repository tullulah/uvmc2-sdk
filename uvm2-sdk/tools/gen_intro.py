#!/usr/bin/env python3
"""The Vectrex Studio intro card (uvm2_intro.c) as one C header: the logo, the wordmark,
a sine table for the logo's turn, and the jingle as IMA ADPCM.

    python3 tools/gen_intro.py <vs_logo.vec> <vs_wordmark.vec> <jingle (mp3/wav/...)> \\
        [VSJINGLE.BIN] > uvm2_intro_data.h

With a fourth argument it also writes the jingle's ADPCM bytes alone to that file: the one a
game built with UVM2_INTRO=sd reads off the card instead of carrying them (uvm2.mk).

The sources are the kuroishi cartridge's (hardware/uvm2/kuroishi: assets/vectors/ and
resources/VectrexStudio.mp3), where the card was drawn first.

THE JINGLE'S SIZE IS THE CONSTRAINT. The card goes into every game that has the OPTIONS
screen, and the image lives in 512 KB of SRAM: aae_mhavoc had 56 KB free above its .bss.
16-bit PCM at the jack's 32 kHz would be 270 KB, mu-law 135 KB. So:
  - 16 kHz, not 32: MEASURED, 1.3% of the recording's energy is above 8 kHz
    (the generator prints it), and uvm2_intro.c doubles it back by interpolation;
  - IMA ADPCM, 4 bits a sample: a quarter of 16-bit, ~34 KB for 4.2 s.
The decoder is ~20 lines in uvm2_intro.c; the encoder below is its exact mirror (it
encodes against its own decoded output), so what is played is what was checked here.
ffmpeg decodes and resamples the source.
"""
import json
import math
import subprocess
import sys

import numpy as np

RATE = 16000
FULL_RATE = 44100   # the rate the source is analysed at, for the energy check only
SIN_STEPS = 256     # a turn; the card turns two in 128 frames, so 4 steps a frame

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55,
        60, 66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307,
        337, 371, 408, 449, 494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411,
        1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358,
        5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500,
        20350, 22385, 24623, 27086, 29794, 32767]
INDEX = [-1, -1, -1, -1, 2, 4, 6, 8]


def ima_encode(x):
    pred, idx, out = 0, 0, []
    for v in x:
        step = STEP[idx]
        d = int(v) - pred
        code = 0
        if d < 0:
            code, d = 8, -d
        diff = step >> 3
        if d >= step:      code |= 4; d -= step;      diff += step
        if d >= step >> 1: code |= 2; d -= step >> 1; diff += step >> 1
        if d >= step >> 2: code |= 1;                 diff += step >> 2
        pred = pred - diff if code & 8 else pred + diff
        pred = max(-32768, min(32767, pred))
        idx = max(0, min(88, idx + INDEX[code & 7]))
        out.append(code)
    if len(out) & 1:
        out.append(0)
    return bytes(out[i] | (out[i + 1] << 4) for i in range(0, len(out), 2))


def load_audio(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(RATE),
                          "-f", "s16le", "-"], check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype="<i2")


def vec_paths(path):
    d = json.load(open(path))
    return [p for layer in d["layers"] if layer.get("visible", True) for p in layer["paths"]]


def emit_paths(sym, paths):
    out = []
    for i, p in enumerate(paths):
        pts = ", ".join(f"{{{q['x']},{q['y']}}}" for q in p["points"])
        out.append(f"static const int8_t {sym}_P{i}[][2] = {{ {pts} }};")
    out.append(f"static const uvm2_intro_path {sym}[] = {{")
    for i, p in enumerate(paths):
        out.append(f"    {{ {sym}_P{i}, {len(p['points'])}, {p.get('intensity', 100)}, "
                   f"{1 if p.get('closed') else 0} }},")
    out.append("};")
    out.append(f"#define {sym}_N {len(paths)}")
    return out


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    logo, mark, song = sys.argv[1:4]
    pcm = load_audio(song)
    spec = np.abs(np.fft.rfft(load_audio_full(song))) ** 2
    adp = ima_encode(pcm)
    names = [s.rsplit("/", 1)[-1] for s in (logo, mark, song)]
    o = ["/* GENERATED by uvm2-sdk/tools/gen_intro.py from " + ", ".join(names) + ".",
         " * Do not edit: re-run it (the sources are in hardware/uvm2/kuroishi). */",
         "#ifndef UVM2_INTRO_DATA_H", "#define UVM2_INTRO_DATA_H", "#include <stdint.h>", "",
         "typedef struct { const int8_t (*pt)[2]; uint8_t n, bright, closed; } uvm2_intro_path;", ""]
    o += emit_paths("VS_LOGO", vec_paths(logo)) + [""]
    o += emit_paths("VS_WORDMARK", vec_paths(mark)) + [""]
    o.append(f"/* sin over a turn of {SIN_STEPS} steps, Q14 */")
    o.append(f"#define VS_SIN_STEPS {SIN_STEPS}")
    sins = [round(16384 * math.sin(2 * math.pi * i / SIN_STEPS)) for i in range(SIN_STEPS)]
    o.append("static const int16_t VS_SIN[VS_SIN_STEPS] = {")
    for k in range(0, SIN_STEPS, 16):
        o.append("    " + ",".join(str(v) for v in sins[k:k + 16]) + ",")
    o.append("};\n")
    o.append(f"/* {names[2]}: {len(pcm)} samples at {RATE} Hz ({len(pcm) / RATE:.2f} s), "
             f"IMA ADPCM, low nibble first. {spec_note(spec)} */")
    o.append(f"#define VS_JINGLE_RATE {RATE}")
    o.append(f"#define VS_JINGLE_SAMPLES {len(pcm)}u")
    o.append(f"#define VS_JINGLE_BYTES {len(adp)}u")
    o.append(f"#define VS_JINGLE_FNV1A 0x{fnv1a(adp):08X}u   /* of the bytes, for VSJINGLE.BIN */")
    o.append("#ifndef UVM2_INTRO_JINGLE_SD   /* with it, the bytes come off the card (uvm2_intro.c) */")
    o.append(f"static const uint8_t VS_JINGLE[{len(adp)}] = {{")
    for k in range(0, len(adp), 24):
        o.append("    " + ",".join(f"0x{b:02x}" for b in adp[k:k + 24]) + ",")
    o.append("};\n#endif\n\n#endif")
    if len(sys.argv) > 4:
        open(sys.argv[4], "wb").write(bytes(adp))
    print("\n".join(o))
    print(f"jingle {len(adp)} bytes, peak {int(np.abs(pcm.astype(int)).max())}, "
          f"{spec_note(spec)}", file=sys.stderr)


def load_audio_full(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(FULL_RATE),
                          "-f", "s16le", "-"],
                         check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype="<i2").astype(np.float64)


def spec_note(spec):
    # the share of the source's energy above what RATE keeps (its Nyquist, RATE/2), measured
    # on the source decoded at FULL_RATE: the bins are spaced FULL_RATE/2 / len(spec).
    cut = int(len(spec) * (RATE / 2) / (FULL_RATE / 2))
    return f"{100 * spec[cut:].sum() / spec.sum():.2f}% of the source's energy above {RATE // 2} Hz"


if __name__ == "__main__":
    main()
